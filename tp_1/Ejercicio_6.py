## lista de numeros ##
numeros = [10, 20, 30, 40, 50]

## mostrar la lista de numeros ##

for numero in numeros:
    print(numero)

## mostrar el primer elemento de la lista ##
print("Primer elemento:", numeros[0])

## mostrar el ultimo elemento de la lista ##
print("Último elemento:", numeros[-1])

## mostrar la cantidad de elementos utilizando la funcion len() ##
print("Cantidad de elementos:", len(numeros))

