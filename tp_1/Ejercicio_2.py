## ingresa un nombre edad y altura ##
nombre = input("Ingrese el nombre: ")
edad = int(input("Ingrese la edad: "))
altura = float(input("Ingrese la altura: "))

## valor ingresado y sus respectivos tipos de datos ##
print("Nombre:", nombre, "Tipo de dato:", type(nombre))
print("Edad:", edad, "Tipo de dato:", type(edad))
print("Altura:", altura, "Tipo de dato:", type(altura))
